def check_network_folder(
    folder,
    year,
    month_number,
    label,
    expected_generators,
    expected_combined_power,
    expected_snapshot_hours,
):
    """
    Verify one generated monthly PyPSA base-network folder.

    The function checks:

        - required exported component files;
        - uniqueness of line names;
        - positive stored AC-line ratings matching independent derivation;
        - component-to-bus integrity;
        - dormant base generators;
        - expected half-hourly snapshot count;
        - HVDC presence or absence;
        - N-50 and N-51 configuration and derived rating.

    Parameters
    ----------
    folder : pathlib.Path
        Path to the monthly PyPSA CSV network.

    year : int
        Network year.

    month_number : int
        Calendar month number, 1 to 12.

    label : str
        Network representation: ``SI``, ``NI`` or ``combined``.

    Returns
    -------
    dict or None
        Dictionary containing component counts if the folder could be
        successfully inspected, otherwise None.
    """
    if not folder.is_dir():
        fail(
            f"Missing network folder: {folder}"
        )
        return None

    required = (
        "buses.csv",
        "lines.csv",
        "generators.csv",
        "loads.csv",
        "loads-p_set.csv",
    )

    for filename in required:

        if not (
            folder / filename
        ).exists():
            fail(
                f"{folder}: missing {filename}"
            )
            return None

    buses = read_component(
        folder / "buses.csv"
    )

    lines = read_component(
        folder / "lines.csv"
    )

    generators = read_component(
        folder / "generators.csv"
    )

    loads = read_component(
        folder / "loads.csv"
    )

    expected_load_count = EXPECTED_LOAD_COUNTS[label]
    if len(loads) != expected_load_count:
        fail(
            f"{folder}: contains {len(loads)} loads; expected "
            f"{expected_load_count} for {label}"
        )

    transformers_path = folder / "transformers.csv"
    transformers = (
        read_component(transformers_path)
        if transformers_path.exists()
        else pd.DataFrame()
    )

    links_path = folder / "links.csv"
    links = (
        read_component(links_path)
        if links_path.exists()
        else pd.DataFrame()
    )

    bus_names = component_names(
        buses,
        folder / "buses.csv",
    )

    # ------------------------------------------------------------------
    # General transmission-line integrity
    # ------------------------------------------------------------------
    if "name" not in lines.columns:
        fail(
            f"{folder}: lines.csv "
            f"has no name column"
        )
        return None

    line_ids = (
        lines["name"]
        .astype(str)
        .str.strip()
    )

    blank_names = line_ids.eq("")

    if blank_names.any():
        fail(
            f"{folder}: blank line names "
            f"at rows "
            f"{list(lines.index[blank_names] + 2)}"
        )

    duplicate_names = (
        line_ids.duplicated(
            keep=False
        )
    )

    if duplicate_names.any():

        dupes = sorted(
            set(
                line_ids[
                    duplicate_names
                ]
            )
        )

        fail(
            f"{folder}: duplicate "
            f"line names {dupes}"
        )

    # ------------------------------------------------------------------
    # Stored AC-line optimisation ratings
    # ------------------------------------------------------------------
    check_stored_line_ratings(folder, lines)

    # ------------------------------------------------------------------
    # Component-to-bus integrity
    # ------------------------------------------------------------------
    for (
        component_name,
        dataframe,
        columns,
    ) in (
        (
            "line",
            lines,
            ("bus0", "bus1"),
        ),
        (
            "generator",
            generators,
            ("bus",),
        ),
        (
            "load",
            loads,
            ("bus",),
        ),
    ):

        for column in columns:

            if column not in dataframe.columns:
                fail(
                    f"{folder}: "
                    f"{component_name} file "
                    f"missing column {column}"
                )
                continue

            referenced = set(
                dataframe[column]
                .astype(str)
                .str.strip()
            )

            missing_buses = sorted(
                referenced
                - bus_names
            )

            if missing_buses:
                fail(
                    f"{folder}: "
                    f"{component_name}.{column} "
                    f"references unknown buses "
                    f"{missing_buses}"
                )

    # ------------------------------------------------------------------
    # Intended generator inventory and electrical connectivity
    # ------------------------------------------------------------------
    check_generator_inventory(folder, generators, expected_generators)

    connected_buses = set()
    for dataframe in (lines, transformers):
        if {"bus0", "bus1"}.issubset(dataframe.columns):
            connected_buses.update(
                dataframe["bus0"].astype(str).str.strip()
            )
            connected_buses.update(
                dataframe["bus1"].astype(str).str.strip()
            )

    if "bus" in generators.columns:
        generator_buses = set(generators["bus"].astype(str).str.strip())
        isolated_generator_buses = sorted(generator_buses - connected_buses)
        if isolated_generator_buses:
            fail(
                f"{folder}: generator buses have no AC line or transformer "
                f"connection {isolated_generator_buses}"
            )

    # ------------------------------------------------------------------
    # Base generators must remain dormant
    # ------------------------------------------------------------------
    if "p_max_pu" in generators.columns:

        p_max = pd.to_numeric(
            generators["p_max_pu"],
            errors="coerce",
        ).fillna(0.0)

        nonzero = (
            p_max.abs()
            > 1e-12
        )

        if nonzero.any():
            fail(
                f"{folder}: base network "
                f"contains "
                f"{int(nonzero.sum())} generators "
                f"with non-zero p_max_pu"
            )

    for component_label, dataframe, attribute in (
        ("generators", generators, "p_nom_extendable"),
        ("lines", lines, "s_nom_extendable"),
        ("transformers", transformers, "s_nom_extendable"),
        ("links", links, "p_nom_extendable"),
    ):
        if attribute not in dataframe.columns or dataframe.empty:
            continue
        extendable = (
            dataframe[attribute]
            .astype(str)
            .str.strip()
            .str.lower()
            .isin({"true", "1", "yes"})
        )
        if extendable.any():
            names = sorted(
                dataframe.loc[extendable, "name"].astype(str).str.strip()
            )
            fail(
                f"{folder}: base network contains extendable "
                f"{component_label} {names}"
            )

    # ------------------------------------------------------------------
    # Monthly half-hourly snapshot count
    # ------------------------------------------------------------------
    try:
        load_ts, snapshots_table = read_network_timeseries(
            folder, "loads-p_set.csv"
        )
    except (FileNotFoundError, ValueError) as exc:
        fail(str(exc))
        return None

    expected_snapshots = (
        calendar.monthrange(
            year,
            month_number,
        )[1]
        * 24
        / expected_snapshot_hours
    )

    if (
        len(load_ts)
        != int(expected_snapshots)
    ):
        fail(
            f"{folder}: "
            f"{len(load_ts)} load snapshots; "
            f"expected {int(expected_snapshots)}"
        )

    for weighting in ("objective", "stores", "generators"):
        if weighting not in snapshots_table.columns:
            fail(f"{folder}: snapshots.csv missing {weighting} weighting")
            continue
        values = pd.to_numeric(snapshots_table[weighting], errors="coerce")
        if values.isna().any() or not values.eq(expected_snapshot_hours).all():
            observed = sorted(values.dropna().unique().tolist())
            fail(
                f"{folder}: {weighting} snapshot weights {observed}; expected "
                f"{expected_snapshot_hours} h"
            )

    if label == "combined":
        expected = expected_combined_power.loc[
            (expected_combined_power.index.year == year)
            & (expected_combined_power.index.month == month_number)
        ]
        actual = load_ts.sum(axis=1)
        if not actual.index.equals(expected.index):
            fail(f"{folder}: combined load timestamps differ from annual source")
        elif not pd.Series(actual).equals(pd.Series(expected)):
            difference = float((actual - expected).abs().max())
            tolerance = max(1e-7, float(expected.abs().max()) * 1e-10)
            if difference > tolerance:
                fail(
                    f"{folder}: combined load propagation differs from independently "
                    f"converted source by up to {difference:.9f} MW"
                )

    # ------------------------------------------------------------------
    # Cook Strait HVDC
    # ------------------------------------------------------------------
    check_hvdc(
        folder,
        label,
    )

    # ------------------------------------------------------------------
    # WKM-MTI circuits
    # ------------------------------------------------------------------
    if label in (
        "NI",
        "combined",
    ):

        for line_id in WKM_MTI_LINES:

            rows = lines.loc[
                line_ids == line_id
            ]

            if len(rows) != 1:
                fail(
                    f"{folder}: expected "
                    f"exactly one {line_id}, "
                    f"found {len(rows)}"
                )
                continue

            row = rows.iloc[0]

            bus0 = str(
                row["bus0"]
            ).strip()

            bus1 = str(
                row["bus1"]
            ).strip()

            line_type = str(
                row["type"]
            ).strip()

            num_parallel = float(
                row["num_parallel"]
            )

            v_nom = float(
                row["v_nom"]
            )

            if {
                bus0,
                bus1,
            } != {
                "WKM",
                "MTI",
            }:
                fail(
                    f"{folder}: {line_id} "
                    f"buses are "
                    f"{bus0}->{bus1}"
                )

            if (
                line_type
                != EXPECTED_WKM_MTI_TYPE
            ):
                fail(
                    f"{folder}: {line_id} "
                    f"type={line_type!r}, "
                    f"expected "
                    f"{EXPECTED_WKM_MTI_TYPE!r}"
                )

            if (
                abs(
                    num_parallel
                    - EXPECTED_WKM_MTI_PARALLEL
                )
                > 1e-9
            ):
                fail(
                    f"{folder}: {line_id} "
                    f"num_parallel="
                    f"{num_parallel}, "
                    f"expected 2"
                )

            if (
                abs(
                    v_nom
                    - EXPECTED_WKM_MTI_V_NOM
                )
                > 1e-9
            ):
                fail(
                    f"{folder}: {line_id} "
                    f"v_nom={v_nom}, "
                    f"expected 220"
                )

            try:
                stored_s_nom = float(row["s_nom"])
            except (KeyError, TypeError, ValueError):
                fail(
                    f"{folder}: {line_id} has no valid stored s_nom"
                )
                continue

            if not math.isclose(
                stored_s_nom,
                EXPECTED_WKM_MTI_S_NOM,
                rel_tol=1e-9,
                abs_tol=1e-6,
            ):
                fail(
                    f"{folder}: {line_id} "
                    f"stored "
                    f"s_nom={stored_s_nom:.6f} MVA, "
                    f"expected "
                    f"{EXPECTED_WKM_MTI_S_NOM:.6f}"
                )

    # ------------------------------------------------------------------
    # Evidence-based conservative equivalent line ratings
    # ------------------------------------------------------------------
    if label in ("NI", "combined"):
        for line_id, expected in EXPECTED_EQUIVALENT_LINE_RATINGS_MVA.items():
            rows = lines.loc[line_ids == line_id]
            if len(rows) != 1:
                fail(
                    f"{folder}: expected exactly one mapped {line_id}, "
                    f"found {len(rows)}"
                )
                continue
            row = rows.iloc[0]
            endpoints = {str(row["bus0"]).strip(), str(row["bus1"]).strip()}
            if endpoints != EXPECTED_EQUIVALENT_LINE_ENDPOINTS[line_id]:
                fail(
                    f"{folder}: mapped {line_id} endpoints are "
                    f"{sorted(endpoints)}, expected "
                    f"{sorted(EXPECTED_EQUIVALENT_LINE_ENDPOINTS[line_id])}"
                )
            try:
                stored = float(row["s_nom"])
            except (KeyError, TypeError, ValueError) as exc:
                fail(f"{folder}: cannot verify mapped {line_id}: {exc}")
                continue
            if not math.isclose(
                stored, expected, rel_tol=1e-9, abs_tol=1e-6
            ):
                fail(
                    f"{folder}: mapped {line_id} s_nom={stored:.6f} MVA, "
                    f"expected conservative equivalent {expected:.6f} MVA"
                )

    generator_capacity = float("nan")
    if "p_nom" in generators.columns:
        generator_capacity = float(
            pd.to_numeric(generators["p_nom"], errors="coerce").sum()
        )

    return {
        "buses": len(buses),
        "lines": len(lines),
        "generators": len(generators),
        "generator_capacity_mw": generator_capacity,
        "loads": len(loads),
    }


