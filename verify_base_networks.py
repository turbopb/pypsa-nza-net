def check_source_file(
    path,
    require_wkm=False,
    expected_explicit_ratings=None,
):
    """
    Verify one authoritative transmission-line source CSV.

    Checks that:

        - the file exists;
        - the ``line`` column exists;
        - line identifiers are non-blank;
        - line identifiers are unique.

    For North Island and combined datasets, the function can additionally
    verify that N-50 and N-51 both exist as double-circuit WKM-MTI lines and
    that the accepted ``s_nom_mva`` values occur on exactly the mapped lines.

    Parameters
    ----------
    path : pathlib.Path
        Path to the transmission source CSV.

    require_wkm : bool, optional
        If True, verify the N-50 and N-51 WKM-MTI circuits.
        Default is False.

    expected_explicit_ratings : dict, optional
        Exact source-data ratings expected in ``s_nom_mva``. If omitted, the
        source must not contain any populated explicit ratings.

    Returns
    -------
    None
    """
    print(f"\nSOURCE: {path}")

    if not path.exists():
        fail(
            f"Missing source file: {path}"
        )
        return

    df = pd.read_csv(
        path,
        dtype=str,
        keep_default_na=False,
    )

    if "line" not in df.columns:
        fail(
            f"{path.name}: missing 'line' column"
        )
        return

    ids = (
        df["line"]
        .astype(str)
        .str.strip()
    )

    blank = ids.eq("")

    duplicate = ids.duplicated(
        keep=False
    )

    print(
        f"  rows             : {len(df)}"
    )

    print(
        f"  blank line IDs   : {int(blank.sum())}"
    )

    print(
        f"  duplicate IDs    : {int(duplicate.sum())}"
    )

    if blank.any():
        fail(
            f"{path.name}: blank line IDs at CSV rows "
            f"{list(df.index[blank] + 2)}"
        )

    if duplicate.any():
        values = sorted(
            set(ids[duplicate])
        )

        fail(
            f"{path.name}: duplicate line IDs "
            f"{values}"
        )

    if "s_nom_mva" not in df.columns:
        if expected_explicit_ratings:
            fail(f"{path.name}: missing required 's_nom_mva' column")
    else:
        raw_ratings = df["s_nom_mva"].astype(str).str.strip()
        populated = raw_ratings.ne("")
        actual_ids = set(ids.loc[populated])
        expected_ids = set((expected_explicit_ratings or {}).keys())

        if actual_ids != expected_ids:
            fail(
                f"{path.name}: populated s_nom_mva line IDs differ from "
                f"the accepted set: actual={sorted(actual_ids)}, "
                f"expected={sorted(expected_ids)}"
            )

        for index in df.index[populated]:
            line_id = ids.loc[index]
            raw_value = raw_ratings.loc[index]
            try:
                rating_mva = float(raw_value)
            except (TypeError, ValueError):
                fail(
                    f"{path.name}: {line_id} has non-numeric "
                    f"s_nom_mva={raw_value!r}"
                )
                continue
            if not math.isfinite(rating_mva) or rating_mva <= 0.0:
                fail(
                    f"{path.name}: {line_id} has invalid "
                    f"s_nom_mva={rating_mva!r}"
                )
                continue
            expected = (expected_explicit_ratings or {}).get(line_id)
            if expected is None:
                continue
            if not math.isclose(
                rating_mva,
                expected,
                rel_tol=0.0,
                abs_tol=1e-9,
            ):
                fail(
                    f"{path.name}: {line_id} s_nom_mva={rating_mva:.6f}, "
                    f"expected {expected:.6f} MVA"
                )
            else:
                print(f"  {line_id}: explicit s_nom_mva={rating_mva:.2f}")

    if require_wkm:

        for line_id in WKM_MTI_LINES:

            rows = df.loc[
                ids == line_id
            ]

            if len(rows) != 1:
                fail(
                    f"{path.name}: expected one "
                    f"{line_id}, found {len(rows)}"
                )
                continue

            row = rows.iloc[0]

            bus0 = str(
                row["bus0"]
            ).strip()

            bus1 = str(
                row["bus1"]
            ).strip()

            config = str(
                row.get("config", "")
            ).strip()

            print(
                f"  {line_id}: "
                f"{bus0}->{bus1}, "
                f"config={config}"
            )

            if {bus0, bus1} != {
                "WKM",
                "MTI",
            }:
                fail(
                    f"{path.name}: {line_id} has "
                    f"unexpected buses "
                    f"{bus0}->{bus1}"
                )

            if config.lower() != "double":
                fail(
                    f"{path.name}: {line_id} "
                    f"config is {config!r}, "
                    f"expected 'double'"
                )


def check_combined_source_union(si_path, ni_path, combined_path):
    """Verify that the combined AC line source is exactly SI plus NI."""
    if not all(path.exists() for path in (si_path, ni_path, combined_path)):
        return

    si = pd.read_csv(si_path, dtype=str, keep_default_na=False)
    ni = pd.read_csv(ni_path, dtype=str, keep_default_na=False)
    combined = pd.read_csv(combined_path, dtype=str, keep_default_na=False)

    required = {"line", "bus0", "bus1", "volts", "config", "distance"}
    for path, dataframe in (
        (si_path, si),
        (ni_path, ni),
        (combined_path, combined),
    ):
        missing = sorted(required - set(dataframe.columns))
        if missing:
            fail(f"{path.name}: cannot check SI + NI union; missing {missing}")
            return

    # The SI table may predate the optional explicit-rating column. Treat a
    # missing column as blank so the combined table can still be checked as an
    # exact source union.
    for dataframe in (si, ni, combined):
        if "s_nom_mva" not in dataframe.columns:
            dataframe["s_nom_mva"] = ""

    union = pd.concat([si, ni], ignore_index=True)

    columns = [
        "line",
        "bus0",
        "bus1",
        "volts",
        "config",
        "distance",
        "s_nom_mva",
    ]

    expected = union[columns].sort_values("line").reset_index(drop=True)
    actual = combined[columns].sort_values("line").reset_index(drop=True)

    if not actual.equals(expected):
        fail(
            "lines_data.csv is not an exact SI + NI union for the checked "
            "line fields"
        )
    else:
        print(
            f"\nSOURCE UNION: {len(si)} SI + {len(ni)} NI = "
            f"{len(combined)} combined AC lines"
        )


def expected_generator_inventory(label, source_path):
    """Build the intended model inventory independently from the builder."""
    for path in (GENERATOR_REGISTRY, NODES, source_path):
        if not path.exists():
            fail(f"Missing generator-inventory source: {path}")
            return None

    registry = pd.read_csv(GENERATOR_REGISTRY, dtype=str)
    nodes = pd.read_csv(NODES, dtype=str)
    source_lines = pd.read_csv(source_path, dtype=str)

    required_registry = {
        "plant_name", "site", "volts_kv", "carrier", "p_nom_mw", "build_year"
    }
    missing_columns = sorted(required_registry - set(registry.columns))
    if missing_columns:
        fail(
            f"{GENERATOR_REGISTRY}: missing columns required for model "
            f"inventory {missing_columns}"
        )
        return None

    required_line_columns = {"bus0", "bus1", "volts"}
    missing_line_columns = sorted(required_line_columns - set(source_lines.columns))
    if missing_line_columns:
        fail(
            f"{source_path}: missing columns required for generator "
            f"connectivity {missing_line_columns}"
        )
        return None

    registry["site"] = registry["site"].str.strip().str.upper()
    registry["volts_kv"] = pd.to_numeric(registry["volts_kv"], errors="coerce")
    registry["p_nom_mw"] = pd.to_numeric(registry["p_nom_mw"], errors="coerce")
    registry["build_year"] = (
        pd.to_numeric(registry["build_year"], errors="coerce")
        .fillna(0)
        .astype(int)
    )

    hly_mask = registry["site"].eq(HLY_SITE)
    if not hly_mask.any():
        fail(f"{GENERATOR_REGISTRY}: no HLY entries available for aggregation")
        return None

    hly_rows = registry.loc[hly_mask]
    hly = hly_rows.iloc[0].copy()
    hly["plant_name"] = "Huntly Power Station (lumped)"
    hly["site"] = HLY_SITE
    hly["volts_kv"] = 220
    hly["carrier"] = HLY_MODEL_CARRIER
    hly["p_nom_mw"] = float(hly_rows["p_nom_mw"].sum())
    hly["build_year"] = HLY_MODEL_BUILD_YEAR

    model = pd.concat(
        [registry.loc[~hly_mask], pd.DataFrame([hly])],
        ignore_index=True,
    )

    if label != "combined":
        if not {"site", "island"}.issubset(nodes.columns):
            fail(f"{NODES}: missing site or island column")
            return None
        site_island = (
            nodes.assign(site=nodes["site"].str.strip().str.upper())
            .drop_duplicates("site")
            .set_index("site")["island"]
            .str.strip()
            .str.upper()
        )
        model_island = model["site"].map(site_island)
        unmapped = sorted(model.loc[model_island.isna(), "site"].unique())
        if unmapped:
            fail(f"Generator sites missing from nodes.csv: {unmapped}")
            return None
        model = model.loc[model_island.eq(label)].copy()

    site_voltages = {}
    for _, line in source_lines.iterrows():
        volts = int(float(line["volts"]))
        for endpoint in ("bus0", "bus1"):
            site = re.sub(
                r"_\d{2,3}$", "", str(line[endpoint]).strip().upper()
            )
            site_voltages.setdefault(site, set()).add(volts)

    resolved_buses = []
    for _, generator in model.iterrows():
        site = generator["site"]
        volts = int(generator["volts_kv"])
        available_voltages = site_voltages.get(site, set())

        if volts not in available_voltages:
            fail(
                f"{source_path.name}: generator {generator['plant_name']} "
                f"at {site} {volts} kV is not connected at that voltage; "
                f"source voltages={sorted(available_voltages)}"
            )

        if len(available_voltages) > 1:
            resolved_buses.append(f"{site}_{volts}")
        else:
            resolved_buses.append(site)

    model["bus"] = resolved_buses
    model["name"] = model["bus"] + "_" + model["carrier"].str.strip()
    model = model.rename(columns={"p_nom_mw": "p_nom"})

    duplicates = sorted(
        model.loc[model["name"].duplicated(keep=False), "name"].unique()
    )
    if duplicates:
        fail(f"Duplicate intended model generator names: {duplicates}")

    expected_summary = EXPECTED_GENERATOR_SUMMARY[label]
    capacity = float(model["p_nom"].sum())
    if len(model) != expected_summary["count"]:
        fail(
            f"{label} intended generator count {len(model)}; expected "
            f"{expected_summary['count']}"
        )
    if abs(capacity - expected_summary["capacity_mw"]) > 1e-6:
        fail(
            f"{label} intended generator capacity {capacity:.6f} MW; "
            f"expected {expected_summary['capacity_mw']:.6f} MW"
        )

    return model.set_index("name")[["bus", "carrier", "p_nom", "build_year"]]


