def check_hvdc(folder, label):
    """
    Verify the Cook Strait HVDC representation.

    The expected network behaviour is:

        combined NZ:
            one HVDC_BEN_HAY link from BEN to HAY_220,
            rated at 1200 MW.

        North Island only:
            no HVDC link.

        South Island only:
            no HVDC link.

    Parameters
    ----------
    folder : pathlib.Path
        Monthly PyPSA network folder.

    label : str
        Network representation: ``SI``, ``NI`` or ``combined``.

    Returns
    -------
    None
    """
    links_path = folder / "links.csv"

    if label == "combined":

        if not links_path.exists():
            fail(
                f"{folder}: combined network "
                f"has no links.csv"
            )
            return

        links = read_component(
            links_path
        )

        if "name" not in links.columns:
            fail(
                f"{folder}: links.csv "
                f"has no name column"
            )
            return

        if len(links) != 1:
            fail(
                f"{folder}: combined network contains {len(links)} links; "
                "expected exactly one simplified HVDC link"
            )

        rows = links.loc[
            links["name"]
            .astype(str)
            .str.strip()
            == EXPECTED_HVDC_NAME
        ]

        if len(rows) != 1:
            fail(
                f"{folder}: expected one "
                f"{EXPECTED_HVDC_NAME}, "
                f"found {len(rows)}"
            )
            return

        row = rows.iloc[0]

        if (
            str(row["bus0"]).strip() != EXPECTED_HVDC_BUS0
            or
            str(row["bus1"]).strip()
            != EXPECTED_HVDC_BUS1
        ):
            fail(
                f"{folder}: HVDC endpoints are "
                f"{row['bus0']}->{row['bus1']}"
            )

        if (
            abs(
                float(row["p_nom"])
                - EXPECTED_HVDC_P_NOM
            )
            > 1e-6
        ):
            fail(
                f"{folder}: HVDC p_nom="
                f"{row['p_nom']}, "
                f"expected {EXPECTED_HVDC_P_NOM:.0f} MW"
            )

        for field, expected in (
            ("p_min_pu", -1.0),
            ("p_max_pu", 1.0),
            ("efficiency", EXPECTED_HVDC_EFFICIENCY),
        ):
            if field not in row.index:
                # PyPSA may omit a static attribute when it equals the
                # component default. Link p_max_pu defaults to 1.0.
                if field == "p_max_pu" and expected == 1.0:
                    continue
                fail(f"{folder}: HVDC link missing {field}")
                continue
            if abs(float(row[field]) - expected) > 1e-6:
                fail(
                    f"{folder}: HVDC {field}={row[field]}, expected {expected}"
                )

    else:

        if not links_path.exists():
            return

        links = read_component(
            links_path
        )

        if len(links) > 0:
            fail(
                f"{folder}: {label} network "
                f"unexpectedly contains "
                f"{len(links)} link component(s)"
            )


