def fixed_interval_hours(frequency):
    """Return hours represented by one fixed pandas interval."""
    try:
        offset = pd.tseries.frequencies.to_offset(frequency)
        hours = offset.nanos / 3_600_000_000_000
    except (TypeError, ValueError) as exc:
        raise ValueError(f"Non-fixed frequency {frequency!r}") from exc
    if not math.isfinite(hours) or hours <= 0:
        raise ValueError(f"Invalid frequency {frequency!r}")
    return float(hours)


def load_timeseries_contract():
    """Load and validate the annual source-data unit contract."""
    if not CONFIG_PATH.exists():
        raise FileNotFoundError(CONFIG_PATH)
    with CONFIG_PATH.open("r", encoding="utf-8") as stream:
        config = yaml.safe_load(stream)

    model_frequency = str(config.get("frequency", "")).strip()
    contract = config.get("annual_timeseries")
    if not isinstance(contract, dict):
        raise ValueError("Config is missing annual_timeseries")
    quantity = str(contract.get("input_quantity", "")).strip().lower()
    unit = str(contract.get("input_unit", "")).strip()
    source_interval = str(contract.get("source_interval", "")).strip()
    if (quantity, unit) not in {
        ("interval_energy", "MWh"),
        ("average_power", "MW"),
    }:
        raise ValueError(
            "annual_timeseries must be interval_energy/MWh or average_power/MW"
        )

    return {
        "quantity": quantity,
        "unit": unit,
        "source_interval": source_interval,
        "source_hours": fixed_interval_hours(source_interval),
        "model_frequency": model_frequency,
        "model_hours": fixed_interval_hours(model_frequency),
    }


def load_expected_combined_power(year, contract):
    """Independently derive combined-network load MW from the annual source."""
    path = ANNUAL / f"{year}_export_sites_all.csv"
    if not path.exists():
        raise FileNotFoundError(path)
    source = pd.read_csv(path, index_col=0, parse_dates=True)
    source.index = pd.DatetimeIndex(pd.to_datetime(source.index, errors="raise"))
    source = source.apply(pd.to_numeric, errors="raise")
    if source.index.has_duplicates or source.isna().any().any():
        raise ValueError(f"{path}: duplicate timestamps or missing values")

    if contract["quantity"] == "interval_energy":
        if contract["model_frequency"] != contract["source_interval"]:
            source = source.resample(contract["model_frequency"]).sum()
        power = source / contract["model_hours"]
    else:
        if contract["model_frequency"] != contract["source_interval"]:
            source = source.resample(contract["model_frequency"]).mean()
        power = source
    return power.sum(axis=1)


def read_network_timeseries(folder, filename):
    """Read a PyPSA timeseries and replace serialized keys with datetimes."""
    snapshots_path = folder / "snapshots.csv"
    snapshots = pd.read_csv(snapshots_path, index_col=0, keep_default_na=False)
    if "snapshot" not in snapshots.columns:
        raise ValueError(f"{snapshots_path}: missing snapshot column")
    index = pd.DatetimeIndex(pd.to_datetime(snapshots["snapshot"], errors="raise"))
    timeseries = pd.read_csv(folder / filename, index_col=0)
    if len(timeseries) != len(index):
        raise ValueError(f"{folder / filename}: snapshot length mismatch")
    timeseries.index = index
    return timeseries.apply(pd.to_numeric, errors="raise"), snapshots


def component_names(df, path):
    """
    Return the component-name set from an exported PyPSA table.

    Parameters
    ----------
    df : pandas.DataFrame
        Component table.

    path : pathlib.Path
        Source path, used in diagnostic error messages.

    Returns
    -------
    set of str
        Set of stripped component names.

    Raises
    ------
    ValueError
        If the component table does not contain a ``name`` column.
    """
    if "name" not in df.columns:
        raise ValueError(
            f"{path}: missing 'name' column"
        )

    return set(
        df["name"]
        .astype(str)
        .str.strip()
    )


def check_generator_inventory(folder, generators, expected):
    """Compare one exported generator table with the intended model inventory."""
    if expected is None:
        fail(f"{folder}: intended generator inventory could not be constructed")
        return

    required = {"name", "bus", "carrier", "p_nom", "build_year"}
    missing_columns = sorted(required - set(generators.columns))
    if missing_columns:
        fail(f"{folder}: generators.csv missing columns {missing_columns}")
        return

    actual = generators.copy()
    actual["name"] = actual["name"].astype(str).str.strip()
    actual["bus"] = actual["bus"].astype(str).str.strip()
    actual["carrier"] = actual["carrier"].astype(str).str.strip()
    actual["p_nom"] = pd.to_numeric(actual["p_nom"], errors="coerce")
    actual["build_year"] = (
        pd.to_numeric(actual["build_year"], errors="coerce")
        .fillna(0)
        .astype(int)
    )

    duplicate_names = sorted(
        actual.loc[actual["name"].duplicated(keep=False), "name"].unique()
    )
    if duplicate_names:
        fail(f"{folder}: duplicate generator names {duplicate_names}")
        return

    actual = actual.set_index("name")
    expected_names = set(expected.index)
    actual_names = set(actual.index)

    missing = sorted(expected_names - actual_names)
    unexpected = sorted(actual_names - expected_names)
    if missing:
        fail(f"{folder}: missing intended generators {missing}")
    if unexpected:
        fail(f"{folder}: unexpected generators {unexpected}")

    for name in sorted(expected_names & actual_names):
        expected_row = expected.loc[name]
        actual_row = actual.loc[name]

        for field in ("bus", "carrier"):
            if str(actual_row[field]) != str(expected_row[field]):
                fail(
                    f"{folder}: {name} {field}={actual_row[field]!r}; "
                    f"expected {expected_row[field]!r}"
                )

        if abs(float(actual_row["p_nom"]) - float(expected_row["p_nom"])) > 1e-6:
            fail(
                f"{folder}: {name} p_nom={actual_row['p_nom']} MW; "
                f"expected {expected_row['p_nom']} MW"
            )

        if int(actual_row["build_year"]) != int(expected_row["build_year"]):
            fail(
                f"{folder}: {name} build_year={actual_row['build_year']}; "
                f"expected {expected_row['build_year']}"
            )

    if HLY_MODEL_NAME in actual.index:
        hly = actual.loc[HLY_MODEL_NAME]
        if str(hly["bus"]) != "HLY" or str(hly["carrier"]) != "gas":
            fail(f"{folder}: lumped HLY generator is not HLY_gas at bus HLY")

    individual_hly = sorted(
        name for name in actual.index
        if name.startswith("HLY_") and name != HLY_MODEL_NAME
    )
    if individual_hly:
        fail(f"{folder}: individual HLY generators remain {individual_hly}")


