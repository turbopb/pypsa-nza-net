"""
verify_base_networks.py

Read-only verification of the PyPSA-NZA base network datasets generated by
nza_base_net.py.

Purpose
-------
This script checks the integrity of the three base-network representations:

    1. South Island only
    2. North Island only
    3. Combined New Zealand network with the Cook Strait HVDC link

The verification is performed for all monthly networks for 2024 and 2025.

The script specifically checks:

    - The three authoritative transmission source files exist and contain
      valid line identifiers.
    - There are no blank or duplicate transmission-line identifiers.
    - The Wairakei-Matahina (WKM-MTI) circuits N-50 and N-51 are present in
      both the North Island and combined source datasets.
    - N-50 and N-51 are represented as double-circuit 220 kV lines.
    - Every exported AC line has a finite, positive stored ``s_nom`` and that
      optimisation limit agrees with the independently derived generic rating
      from its PyPSA standard line type, voltage and circuit count, including
      only the explicitly mapped conservative Upper North Island equivalent
      ratings.
    - The stored thermal ratings of N-50 and N-51 are correct.
    - All expected SI, NI and combined monthly network folders exist.
    - Required PyPSA component CSV files exist.
    - Transmission lines, generators and loads reference valid buses.
    - The 52-row global generator registry is transformed into the intended
      50-generator model inventory by lumping the three HLY records into one
      1203 MW HLY_gas generator while retaining MAT_hydro separately.
    - Every intended generator is connected at its registered voltage in the
      authoritative AC line data and has an AC connection in the network.
    - Base-network generators remain dormant prior to customisation.
    - No generator, line, transformer or HVDC link is extendable in the
      operational reference-network foundation.
    - Monthly load timeseries contain the expected number of half-hourly
      snapshots.
    - Exactly one simplified Cook Strait HVDC link exists in combined NZ
      networks and no HVDC link exists in island-only networks.
    - Network topology is consistent from month to month.

Important
---------
This is a read-only diagnostic script. It does not modify source data,
network files, configuration files, or PyPSA models.

Unless its authoritative source row supplies ``s_nom_mva``, the thermal
rating of a typed PyPSA AC line is derived as:

    S_nom = sqrt(3) * V_nom * I_nom * num_parallel

where:

    V_nom         = nominal line voltage in kV
    I_nom         = line-type current rating in kA
    num_parallel  = number of parallel circuits

The resulting S_nom is in MVA. A populated ``s_nom_mva`` is an explicit
base-network rating and replaces this generic proxy for that line only.

Usage
-----
From the pypsa-nza-net repository:

    python verify_base_networks.py

Author
------
Phillippe Bruneau

Project
-------
pypsa-nza / Transition Energy Feasibility Framework (TEFF)
"""

