def derived_s_nom(row):
    """
    Derive the apparent-power rating of a typed PyPSA AC line.

    The expected line rating is independently calculated from:

        S_nom = sqrt(3) * V_nom * I_nom * num_parallel

    Parameters
    ----------
    row : pandas.Series
        Row from an exported PyPSA ``lines.csv`` file. It must contain
        ``type``, ``v_nom`` and ``num_parallel``.

    Returns
    -------
    float
        Derived apparent-power rating in MVA.

    Raises
    ------
    KeyError
        If the exported line type cannot be found in PyPSA's standard
        line-type library.
    """
    line_type = str(row["type"]).strip()

    if line_type not in TYPE_LIBRARY.index:
        raise KeyError(
            f"Unknown PyPSA line type: {line_type}"
        )

    i_nom = float(
        TYPE_LIBRARY.loc[line_type, "i_nom"]
    )

    v_nom = float(row["v_nom"])

    num_parallel = float(
        row["num_parallel"]
    )

    return (
        math.sqrt(3.0)
        * v_nom
        * i_nom
        * num_parallel
    )


def check_stored_line_ratings(folder, lines):
    """Verify the actual optimisation rating stored for every AC line."""
    required = {"name", "type", "v_nom", "num_parallel", "s_nom"}
    missing_columns = sorted(required - set(lines.columns))

    if missing_columns:
        fail(
            f"{folder}: lines.csv missing rating columns {missing_columns}"
        )
        return

    line_names = lines["name"].astype(str).str.strip()
    stored_s_nom = pd.to_numeric(lines["s_nom"], errors="coerce")
    finite = stored_s_nom.map(
        lambda value: pd.notna(value) and math.isfinite(float(value))
    )
    valid = finite & stored_s_nom.gt(0.0)

    if (~valid).any():
        invalid_names = sorted(line_names.loc[~valid].tolist())
        fail(
            f"{folder}: AC lines have missing, non-numeric, non-finite, "
            f"or non-positive stored s_nom values {invalid_names}"
        )

    derivation_errors = []
    mismatches = []

    for index, row in lines.loc[valid].iterrows():
        line_name = line_names.loc[index]

        try:
            generic_s_nom = derived_s_nom(row)
            expected_s_nom = EXPECTED_EQUIVALENT_LINE_RATINGS_MVA.get(
                line_name,
                generic_s_nom,
            )
        except Exception as exc:
            derivation_errors.append(f"{line_name}: {exc}")
            continue

        if not math.isfinite(expected_s_nom) or expected_s_nom <= 0.0:
            derivation_errors.append(
                f"{line_name}: derived s_nom={expected_s_nom!r}"
            )
            continue

        actual_s_nom = float(stored_s_nom.loc[index])
        if not math.isclose(
            actual_s_nom,
            expected_s_nom,
            rel_tol=1e-9,
            abs_tol=1e-6,
        ):
            mismatches.append(
                f"{line_name} stored={actual_s_nom:.6f} MVA "
                f"expected={expected_s_nom:.6f} MVA "
                f"(generic proxy={generic_s_nom:.6f} MVA)"
            )

    if derivation_errors:
        fail(
            f"{folder}: cannot independently derive AC line ratings: "
            + "; ".join(derivation_errors)
        )

    if mismatches:
        fail(
            f"{folder}: stored AC line s_nom values do not match their "
            f"independently derived ratings: "
            + "; ".join(mismatches)
        )


